# โจทย์ข้อที่ 2: บวกเลข 2 จำนวน
# Input: บรรทัดที่ 1 ตัวเลขแรก (จำนวนเต็ม)
#        บรรทัดที่ 2 ตัวเลขที่สอง (จำนวนเต็ม)
# Output: ผลบวกของตัวเลขทั้งสอง
# ==========================================

# นักเรียนเขียนโค้ดต่อจากบรรทัดนี้
a = int(input("จํานวนที่1: "))
b= int(input("จํานวนที่2: "))
total= a + b
print(f"ผลบวกของเลขทั้ง2:{total}")
